import { readFile, writeFile } from 'node:fs/promises';
// Brand assets are embedded so the server and npm package need no extra files at runtime.
const files = ['favicon.ico', 'icon.svg', 'logo.svg', 'app-icon.png'];
const media = {};
for (const name of files) media[name] = (await readFile(new URL(`../src/media/${name}`, import.meta.url))).toString('base64');
await writeFile(new URL('../src/media-assets.ts', import.meta.url), '// Generated by scripts/embed-media.mjs from src/media.\nexport const media = ' + JSON.stringify(media) + ' as const;\n');
