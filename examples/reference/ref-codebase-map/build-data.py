#!/usr/bin/env python3
"""Regenerate data.js for the codebase map from git.

    python3 examples/reference/ref-codebase-map/build-data.py

Reads `git ls-files`, untracked-but-not-ignored files, `git log --numstat` and the
working-tree diff, so uncommitted work shows up as "modified" or "new".
Hand-written purpose blurbs live in notes.js and are never touched by this script.
"""
import json, os, re, subprocess, datetime, collections

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = subprocess.check_output(["git", "rev-parse", "--show-toplevel"], cwd=HERE, text=True).strip()

# What a reader cares about: source, tests, scripts, docs, config and the reference artifacts.
EXCLUDE = [
    r"^node_modules/", r"^dist/", r"^release/artifact-linux", r"(^|/)package-lock\.json$",
    r"^examples/reference/[^/]+/shots/", r"^examples/reference/kit/fonts/", r"\.(png|webp|jpe?g|gif|ico|mp4|woff2?|tgz)$",
    r"^src/bundled-skill\.ts$", r"^src/media-assets\.ts$",  # generated
    r"^examples/reference/[^/]+/(shots\.json|shots\.js|diff\.js)$",  # generated evidence data
    r"^examples/reference/(ref-codebase-map|ref-weekly-digest)/data\.js$",  # generated by build-data.py
]
TYPES = [  # (label, extensions) — order = colour slot order
    ("TypeScript", (".ts",)), ("HTML", (".html",)), ("CSS", (".css",)), ("JavaScript", (".js", ".mjs")),
    ("Docs & config", (".md", ".json", ".yaml", ".yml", ".txt", ".svg", ".csv", ".sh", ".py", ".toml")),
]

def git(*args):
    return subprocess.check_output(["git", *args], cwd=ROOT, text=True)

def excluded(path):
    return any(re.search(p, path) for p in EXCLUDE)

def file_type(path):
    for label, exts in TYPES:
        if path.endswith(exts):
            return label
    if os.path.basename(path).startswith(("Dockerfile", ".")):
        return "Docs & config"
    return "Other"

def area(path):
    parts = path.split("/")
    if parts[0] == "examples" and len(parts) > 2 and parts[1] == "reference":
        return "examples/reference/" + parts[2] if len(parts) > 3 else "examples/reference"
    if parts[0] == "examples" and len(parts) > 2:
        return "examples/" + parts[1]
    return parts[0] if len(parts) > 1 else "(root)"

def count_lines(full):
    try:
        with open(full, "rb") as fh:
            data = fh.read()
    except OSError:
        return None
    if b"\0" in data[:8192]:
        return None
    return data.count(b"\n") + (0 if data.endswith(b"\n") or not data else 1)

tracked = set(git("ls-files").split("\n")) - {""}
untracked = set(git("ls-files", "--others", "--exclude-standard").split("\n")) - {""}
modified = set(git("diff", "--name-only", "HEAD").split("\n")) - {""}

# History: per-file commit counts, lines added/removed and the date of the last change.
# Only numbers and dates are kept: no commit hashes, authors or messages end up in the page.
stats = collections.defaultdict(lambda: {"commits": 0, "added": 0, "removed": 0, "last": None, "created": 0})
commits = []
current = None
for line in git("log", "--numstat", "--date=iso-strict", "--format=@@%ad").split("\n"):
    if line.startswith("@@"):
        current = {"date": line[2:]}
        commits.append(current)
    elif line.strip() and current:
        a, r, path = line.split("\t", 2)
        if "=>" in path:
            continue
        s = stats[path]
        s["commits"] += 1
        s["created"] = int(a) if a.isdigit() else 0  # log is newest first, so the last one seen is the creation
        s["added"] += int(a) if a.isdigit() else 0
        s["removed"] += int(r) if r.isdigit() else 0
        if s["last"] is None:
            s["last"] = current["date"]

# Working tree changes count as churn too, so in-progress work is visible.
for line in git("diff", "--numstat", "HEAD").split("\n"):
    if line.strip():
        a, r, path = line.split("\t", 2)
        stats[path]["wipAdded"] = int(a) if a.isdigit() else 0
        stats[path]["wipRemoved"] = int(r) if r.isdigit() else 0

files = []
for path in sorted(tracked | untracked):
    if excluded(path) or not os.path.isfile(os.path.join(ROOT, path)):
        continue
    lines = count_lines(os.path.join(ROOT, path))
    if not lines:
        continue
    s = stats.get(path, {})
    status = "new" if path in untracked else "modified" if path in modified else "committed"
    wip_a = lines if status == "new" else s.get("wipAdded", 0)
    wip_r = s.get("wipRemoved", 0)
    files.append({
        "path": path, "lines": lines, "type": file_type(path), "area": area(path), "status": status,
        "commits": s.get("commits", 0), "added": s.get("added", 0), "removed": s.get("removed", 0),
        "wip": wip_a + wip_r, "churn": s.get("added", 0) + s.get("removed", 0) + wip_a + wip_r,
        # Edits = every line added or removed after the file was first written (creation excluded).
        "edits": 0 if status == "new" else max(0, s.get("added", 0) - s.get("created", 0)) + s.get("removed", 0) + wip_a + wip_r,
        "last": s.get("last"),
    })

# Module graph of src/*.ts from relative imports.
nodes, edges = [], []
GENERATED = {"src/bundled-skill.ts": "scripts/embed-skill.mjs", "src/media-assets.ts": "scripts/embed-media.mjs"}
for name in sorted(os.listdir(os.path.join(ROOT, "src"))):
    if name.endswith(".ts"):
        nodes.append("src/" + name)
for path in nodes:
    text = open(os.path.join(ROOT, path), encoding="utf8").read()
    for target in sorted(set(re.findall(r"""from\s+['"]\./([\w.-]+)\.js['"]""", text))):
        dep = f"src/{target}.ts"
        if dep in nodes:
            type_only = bool(re.search(r"""import\s+type\s+[^;]*?from\s+['"]\./%s\.js['"]""" % re.escape(target), text)) and not re.search(
                r"""import\s+(?!type)[^;]*?from\s+['"]\./%s\.js['"]""" % re.escape(target), text)
            edges.append({"from": path, "to": dep, "typeOnly": type_only})

data = {
    "generatedAt": datetime.datetime.now(datetime.timezone.utc).isoformat(timespec="seconds"),
    "branch": git("rev-parse", "--abbrev-ref", "HEAD").strip(),
    "types": [t[0] for t in TYPES] + ["Other"],
    "commits": commits, "files": files, "graph": {"nodes": nodes, "edges": edges, "generated": GENERATED},
    "excluded": "node_modules, dist, the release binary, package-lock.json, generated src files, images, fonts and screenshots",
}
with open(os.path.join(HERE, "data.js"), "w", encoding="utf8") as out:
    out.write("/* Generated by build-data.py — do not edit by hand; re-run the script instead. */\n")
    out.write("window.MAP = " + json.dumps(data, indent=1, ensure_ascii=False) + ";\n")
print(f"{len(files)} files, {sum(f['lines'] for f in files)} lines, {len(nodes)} modules, {len(edges)} imports, {len(commits)} commits")
