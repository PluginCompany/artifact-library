#!/usr/bin/env python3
r"""Snapshot a change into diff.js (window.DIFF) for the walkthrough.

    python3 snapshot.py --base v0.3.3 --label 0.3.3                  # base..working tree, src/ and tests/
    python3 snapshot.py --base main --label main --paths src tests docs
    python3 snapshot.py --base v0.3.3 --head v0.4.0 --label 0.3.3    # between two refs
    python3 snapshot.py --base v0.3.3 --label 0.3.3 --redact 'old\.internal\.host=private.example'

Tracked files come from `git diff <base> [<head>]`; files that are new in the working tree
(untracked, not ignored) are included whole as added. The base is shown by its --label, never
by commit hash. --redact REGEX=TEXT (repeatable) rewrites matching text on every diff line, for
private hostnames that appear in removed code; it never changes hunks or line numbers.
Re-run after the change moves on, then re-check the line ranges in data.js."""
import argparse, datetime, json, pathlib, re, subprocess

ROOT = pathlib.Path(__file__).resolve().parents[3]
OUT = pathlib.Path(__file__).with_name("diff.js")
MAX_LINE = 320  # very long lines (inline CSS) are clipped for display


def git(*args):
    return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True, check=True).stdout


def clip(text):
    return text if len(text) <= MAX_LINE else text[:MAX_LINE] + f" …(+{len(text) - MAX_LINE} chars)"


def parse(diff_text):
    files, cur, hunk, status = {}, None, None, "modified"
    for line in diff_text.splitlines():
        if line.startswith("diff --git"):
            cur, hunk, status = None, None, "modified"
        elif line.startswith("new file mode"):
            status = "added"
        elif line.startswith("deleted file mode"):
            status = "deleted"
        elif line.startswith("+++ "):
            path = line[6:] if line.startswith("+++ b/") else None
            if path is None:  # deleted file: take the path from the --- line we skipped
                continue
            cur = {"path": path, "status": status, "hunks": []}
            files[path] = cur
        elif line.startswith("@@") and cur is not None:
            m = re.match(r"@@ -(\d+)(?:,\d+)? \+(\d+)(?:,\d+)? @@ ?(.*)", line)
            hunk = {"old": int(m.group(1)), "new": int(m.group(2)), "context": m.group(3), "lines": []}
            cur["hunks"].append(hunk)
        elif hunk is not None and cur is not None and line[:1] in (" ", "+", "-"):
            hunk["lines"].append([{" ": "ctx", "+": "add", "-": "del"}[line[0]], clip(line[1:])])
    return files


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--base", required=True, help="git ref to compare against (tag, branch or commit)")
    ap.add_argument("--head", help="second ref; default: the working tree")
    ap.add_argument("--label", required=True, help="how the base is named on the page, e.g. 0.3.3")
    ap.add_argument("--paths", nargs="+", default=["src", "tests"], help="paths to include")
    ap.add_argument("--redact", action="append", default=[], metavar="REGEX=TEXT", help="replace private text on diff lines")
    args = ap.parse_args()
    redactions = [(re.compile(r.split("=", 1)[0]), r.split("=", 1)[1]) for r in args.redact]

    refs = [args.base] + ([args.head] if args.head else [])
    files = parse(git("diff", "-U4", *refs, "--", *args.paths))
    if not args.head:
        for path in git("ls-files", "--others", "--exclude-standard", "--", *args.paths).split():
            text = (ROOT / path).read_text().splitlines()
            files[path] = {"path": path, "status": "added",
                           "hunks": [{"old": 0, "new": 1, "context": "", "lines": [["add", clip(t)] for t in text]}]}
    redacted = 0
    for f in files.values():
        for h in f["hunks"]:
            for line in h["lines"]:
                for rx, text in redactions:
                    line[1], n = rx.subn(text, line[1])
                    redacted += n
        f["added"] = sum(1 for h in f["hunks"] for k, _ in h["lines"] if k == "add")
        f["removed"] = sum(1 for h in f["hunks"] for k, _ in h["lines"] if k == "del")
    files = dict(sorted(files.items()))
    data = {"baseLabel": args.label, "headLabel": args.head or "working tree", "paths": args.paths,
            "capturedAt": datetime.datetime.now().astimezone().isoformat(timespec="minutes"), "files": files}
    OUT.write_text("/* Generated by snapshot.py — do not edit by hand. */\nwindow.DIFF = " + json.dumps(data, indent=1) + ";\n")
    print(f"wrote {OUT.name}: {len(files)} files, +{sum(f['added'] for f in files.values())} −{sum(f['removed'] for f in files.values())}")
    if redactions:
        print(f"redacted {redacted} occurrence(s)")
    for f in files.values():
        print(f"  {f['status']:<8} {f['path']:<32} hunks {len(f['hunks']):>2}  +{f['added']} −{f['removed']}")


if __name__ == "__main__":
    main()
